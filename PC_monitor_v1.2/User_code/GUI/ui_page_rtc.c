#include "ui_page_rtc.h"
#include "OLED.h"
#include "rtc.h"

#include <stdint.h>

/* ============================================================
 * 将0~99转换为两个ASCII字符
 *
 * 例如：
 * 8  -> "08"
 * 25 -> "25"
 * ============================================================ */
static void UI_RTC_U8To2Char(char *buf, uint8_t value)
{
    buf[0] = (char)('0' + value / 10);
    buf[1] = (char)('0' + value % 10);
}

/* ============================================================
 * 生成时间字符串
 *
 * HH:MM:SS
 *
 * 例如：
 * 23:55:08
 * ============================================================ */
static void UI_RTC_MakeTimeString(char *buf,
                                  const RTC_TimeTypeDef *time)
{
    UI_RTC_U8To2Char(&buf[0], time->Hours);
    buf[2] = ':';

    UI_RTC_U8To2Char(&buf[3], time->Minutes);
    buf[5] = ':';

    UI_RTC_U8To2Char(&buf[6], time->Seconds);
    buf[8] = '\0';
}

/* ============================================================
 * 生成日期字符串
 *
 * YYYY-MM-DD
 *
 * 例如：
 * 2026-08-31
 * ============================================================ */
static void UI_RTC_MakeDateString(char *buf,
                                  const RTC_DateTypeDef *date)
{
    buf[0] = '2';
    buf[1] = '0';

    UI_RTC_U8To2Char(&buf[2], date->Year);
    buf[4] = '-';

    UI_RTC_U8To2Char(&buf[5], date->Month);
    buf[7] = '-';

    UI_RTC_U8To2Char(&buf[8], date->Date);
    buf[10] = '\0';
}

/* ============================================================
 * 第三页：环境数据 / RTC
 *
 * 页面布局：
 *
 * +--------------------------------+
 * | ENV / RTC                 3/3  |
 * +--------------------------------+
 * | 23:55:08          2026-08-31   |
 * +---------------+----------------+
 * |     TEMP      |      HUM       |
 * |      -- C     |       -- %     |
 * |               |                |
 * +---------------+----------------+
 *
 * 当前没有安装温湿度传感器，
 * 因此使用"--"作为占位符。
 *
 * 后续加入传感器以后，只需要把"--"
 * 替换为实际数值。
 * ============================================================ */
void UI_PageRTC_Draw(void)
{
    RTC_TimeTypeDef rtc_time = {0};
    RTC_DateTypeDef rtc_date = {0};

    char time_buf[9];
    char date_buf[11];

    /* ========================================================
     * 读取RTC
     * ======================================================== */
    if (HAL_RTC_GetTime(
            &hrtc,
            &rtc_time,
            RTC_FORMAT_BIN) != HAL_OK)
    {
        return;
    }
    if (HAL_RTC_GetDate(
            &hrtc,
            &rtc_date,
            RTC_FORMAT_BIN) != HAL_OK)
    {
        return;
    }
	/* 每天更新一次日期 */
	RTC_BackupDate_Update(&rtc_date);
    /* ========================================================
     * 生成RTC字符串
     * ======================================================== */
    UI_RTC_MakeTimeString(
        time_buf,
        &rtc_time
    );
    UI_RTC_MakeDateString(
        date_buf,
        &rtc_date
    );

    /* ========================================================
     * 第一行：页面标题
     * ======================================================== */
    OLED_ShowString(
        0,
        0,
        "ENV / RTC",
        OLED_6X8
    );
    OLED_ShowString(
        110,
        0,
        "3/3",
        OLED_6X8
    );
    /* 顶部分隔线 */
    OLED_DrawLine(
        0,
        9,
        127,
        9
    );

    /* ========================================================
     * 第二行：RTC辅助信息
     *
     * 时间放左侧
     * 日期放右侧
     *
     * 时间宽度：
     * 8 * 6 = 48 pixel
     *
     * 日期宽度：
     * 10 * 6 = 60 pixel
     * ======================================================== */
    OLED_ShowString(
        0,
        12,
        time_buf,
        OLED_6X8
    );
    OLED_ShowString(
        68,
        12,
        date_buf,
        OLED_6X8
    );

    /* RTC区域与环境数据区域分隔线 */
    OLED_DrawLine(
        0,
        22,
        127,
        22
    );

    /* ========================================================
     * 温湿度区域中间分隔线
     * ======================================================== */
    OLED_DrawLine(
        63,
        23,
        63,
        63
    );

    /* ========================================================
     * 温度区域标题
     *
     * 左半屏范围：
     * x = 0 ~ 62
     *
     * TEMP：
     * 4 * 8 = 32 pixel
     *
     * x = 15左右居中
     * ======================================================== */
    OLED_ShowString(
        15,
        25,
        "TEMP",
        OLED_8X16
    );

    /* ========================================================
     * 温度大数据显示
     *
     * 当前无传感器：
     * 使用"--"占位
     *
     * 2个12x24字符：
     * 宽度 = 24 pixel
     * ======================================================== */
    OLED_ShowString(
        13,
        40,
        "--",
        OLED_12X24
    );
    /*
     * 温度单位
     *
     * 当前先使用C。
     * 如果已有Degree图片，也可以后续改成：
     *
     * °C
     */
    OLED_ShowChar(
        42,
        51,
        'C',
        OLED_6X8
    );
    /* ========================================================
     * 湿度区域标题
     *
     * 右半屏范围：
     * x = 64 ~ 127
     * ======================================================== */
    OLED_ShowString(
        80,
        25,
        "HUM",
        OLED_8X16
    );
    /* ========================================================
     * 湿度大数据显示
     * ======================================================== */
    OLED_ShowString(
        78,
        40,
        "--",
        OLED_12X24
    );
    /* 湿度单位 */
    OLED_ShowChar(
        107,
        51,
        '%',
        OLED_6X8
    );
}
